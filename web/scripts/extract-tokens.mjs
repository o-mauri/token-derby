// One-off: copies the old site's design tokens into --td-* token and theme files, 1:1.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, '../../site/public/styles.css'), 'utf8');
const out = resolve(here, '../projects/ui/styles');

const RENAME = {
  bg: 'surface', panel: 'surface-raised', text: 'text', muted: 'text-muted',
  accent: 'accent', border: 'border', live: 'live', 'ticker-accent': 'highlight',
  error: 'error', 'error-wash': 'error-wash', 'pixel-font': 'font-pixel',
  'rarity-common': 'rarity-common', 'rarity-rare': 'rarity-rare', 'rarity-epic': 'rarity-epic',
  'rarity-legendary': 'rarity-legendary', 'rarity-limited': 'rarity-limited',
  lane: 'track-lane', 'lane-alt': 'track-lane-alt', 'track-blend': 'track-blend',
  'track-shade': 'track-shade', 'track-wash': 'track-wash', 'wash-blend': 'track-wash-blend',
  rail: 'track-rail', 'label-box': 'track-label', 'wash-tile': 'track-wash-tile',
};
const THEMES = {
  midnight: ':root[data-theme="midnight"]', turf: ':root[data-theme="turf"]',
  photo: ':root[data-theme="photo"]', london: ':root[data-theme="london"]',
  chromatic: ':root[data-theme="chromatic"]',
  'phosphor-matrix': ':root:is([data-theme="phosphor"], [data-theme="matrix"])',
};

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');
const renameVars = (v) => v.replace(/var\(--([a-z-]+)/g, (m, n) => (RENAME[n] ? `var(--td-${RENAME[n]}` : m));

// Top-level blocks only: "selector { body }" with no nesting inside body.
function blocks(selector) {
  const found = [];
  const src = stripComments(css);
  let i = 0;
  while ((i = src.indexOf(selector + ' {', i)) !== -1) {
    const before = src[i - 1];
    if (i > 0 && before !== '\n') { i += selector.length; continue; }
    const end = src.indexOf('}', i);
    found.push(src.slice(src.indexOf('{', i) + 1, end));
    i = end;
  }
  return found;
}

function decls(bodies) {
  const res = [];
  for (const body of bodies) {
    for (const d of body.split(';')) {
      const m = d.trim().match(/^--([a-z-]+)\s*:\s*([\s\S]+)$/);
      if (m && RENAME[m[1]]) res.push([`--td-${RENAME[m[1]]}`, renameVars(m[2].replace(/\s+/g, ' ').trim())]);
    }
  }
  return res;
}

const header = '/* Generated by scripts/extract-tokens.mjs from site/public/styles.css. */\n';
const fmt = (sel, ds) => `${header}${sel} {\n${ds.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

const base = decls(blocks(':root'));
// Owner-approved v2 tokens live in tokens-added.css; fold them into the JSON for the Colours story.
const added = [...readFileSync(resolve(out, 'tokens-added.css'), 'utf8').matchAll(/(--td-[a-z-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]);
writeFileSync(resolve(out, 'tokens.css'), fmt(':root', base));
const json = { derby: Object.fromEntries([...base, ...added]) };
for (const [id, sel] of Object.entries(THEMES)) {
  const ds = decls(blocks(sel));
  writeFileSync(resolve(out, `themes/${id}.css`), fmt(sel, ds));
  json[id] = Object.fromEntries(ds);
}
writeFileSync(resolve(out, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
